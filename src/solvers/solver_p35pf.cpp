std::tuple<Eigen::Matrix3d, Eigen::Vector3d, double> solver_p35pf(const Eigen::Matrix<double, 2, 4> &y_orig,
                                                                  const Eigen::Matrix<double, 3, 4> &X) {

    bool use_normalization = true;

    double scale = 1.0;
    if (use_normalization) {
        scale = y_orig.colwise().norm().mean() / sqrt(2);
    }
    Eigen::Matrix<double, 2, 4> y = y_orig / scale;

    Eigen::Matrix<double, 8, 12> M;
    M.setZero();
    for (int i = 0; i < 4; i++) {
        M(2 * i, 0) = X(0, i);
        M(2 * i, 1) = X(1, i);
        M(2 * i, 2) = X(2, i);
        M(2 * i, 3) = 1;
        M(2 * i, 8) = -y(0, i) * X(0, i);
        M(2 * i, 9) = -y(0, i) * X(1, i);
        M(2 * i, 10) = -y(0, i) * X(2, i);
        M(2 * i, 11) = -y(0, i);
        M(2 * i + 1, 4) = X(0, i);
        M(2 * i + 1, 5) = X(1, i);
        M(2 * i + 1, 6) = X(2, i);
        M(2 * i + 1, 7) = 1;
        M(2 * i + 1, 8) = -y(1, i) * X(0, i);
        M(2 * i + 1, 9) = -y(1, i) * X(1, i);
        M(2 * i + 1, 10) = -y(1, i) * X(2, i);
        M(2 * i + 1, 11) = -y(1, i);
    }
    Eigen::FullPivHouseholderQR<Eigen::MatrixXd> qr(M.transpose() * M);
    Eigen::MatrixXd Q = qr.matrixQ();
    Eigen::Matrix<double, 12, 5> N = Q.rightCols<5>();
    Eigen::VectorXd data(Eigen::Map<Eigen::VectorXd>(N.data(), N.cols() * N.rows()));

    // Run solver
    Eigen::MatrixXd output = ECCV2026::gb_solver_p35pf(data);

    // We have a 3.5 point method, so we can find the correct solution
    Eigen::MatrixXd P_tmp;
    Eigen::MatrixXd P(4,3);
    P.setZero();
    double min_err = std::numeric_limits<double>::max();

    double err;
    for (int i = 0; i < output.cols(); i++) {
        Eigen::VectorXd data = N * output.col(i).homogeneous();
        P_tmp = Eigen::Map<Eigen::MatrixXd>(data.data(), 4, 3);
        P_tmp.transposeInPlace();

        // Reprojection error
        err = 0;
        for (int j = 0; j < 4; j++) {
            Eigen::Vector3d PXi = P_tmp * X.col(j).homogeneous();
            err += (y.col(j) - PXi.hnormalized()).squaredNorm();
        }

        if (err < min_err) {
            P = P_tmp;
            min_err = err;
        }
    }

    // Decompose pose
    if (P.block<3, 3>(0, 0).determinant() < 0) {
        P = -P;
    }

    P = P / P.block<1, 3>(2, 0).norm();
    double fx = P.block<1, 3>(0, 0).norm();
    double fy = P.block<1, 3>(1, 0).norm();
    P.row(0) = P.row(0) / fx;
    P.row(1) = P.row(1) / fy;

    // Package output to expected format
    Eigen::Matrix3d R = P.block<3, 3>(0, 0);
    Eigen::Vector3d t = P.block<3, 1>(0, 3);
    double f = 0.5 * (fx + fy);

    // Renormalize
    f *= scale;

    return std::make_tuple(R, t, f);
}

